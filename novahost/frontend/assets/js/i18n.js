const DICTIONARIES = { ar: AR, en: EN };
export const LOCALES = [
  { code: 'ar', label: 'العربية', dir: 'rtl' },
  { code: 'en', label: 'English', dir: 'ltr' },
];

let current = 'ar';
const listeners = new Set();

export function getLocale() {
  return current;
}

export function getDirection() {
  return LOCALES.find((l) => l.code === current)?.dir ?? 'ltr';
}

export function setLocale(code) {
  if (!DICTIONARIES[code] || code === current) return;
  current = code;
  applyDocumentLocale();
  for (const listener of listeners) listener(code);
}

export function onLocaleChange(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function applyDocumentLocale() {
  document.documentElement.lang = current;
  document.documentElement.dir = getDirection();
}

/**
 * Translate. Unknown keys fall back to English, then to the key itself — so a
 * missing translation shows up as a readable string rather than a blank space.
 * `{name}` placeholders are substituted from `vars`.
 */
export function t(key, vars = null) {
  let text = DICTIONARIES[current]?.[key] ?? EN[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

/** Translate an API error object into a sentence for the current language. */
export function translateError(error) {
  if (!error) return t('error.generic');
  const code = error.code ?? error;
  const key = `error.${code}`;
  const translated = DICTIONARIES[current]?.[key] ?? EN[key];
  if (translated) return translated;
  // No translation for this code: the server's English message is still more
  // useful to the operator than a generic "something went wrong".
  return error.message || t('error.generic');
}
